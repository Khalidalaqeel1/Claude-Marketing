function fmtTime(min) {
  const m = Math.floor(min);
  const s = Math.round((min - m) * 60);
  return s ? `${m}:${String(s).padStart(2, "0")} دقيقة` : `${m}:00 ${m === 1 ? "دقيقة" : "دقائق"}`;
}

function notesText(i) {
  const n = NOTES[i];
  const out = [
    `الشريحة ${i + 1}: ${n.title}`,
    `الوقت التقريبي: ${fmtTime(n.minutes)}`,
    "",
    `الفكرة الرئيسية: ${n.main}`,
    "",
    `كيف تقولها: ${n.say}`,
  ];
  if (n.example) out.push("", `مثال: ${n.example}`);
  out.push("", "مصدر المحتوى:");
  for (const [tag, txt] of n.sources) out.push(`[${tag}] ${txt}`);
  out.push("", `الانتقال: ${n.transition}`);
  return out.join("\n");
}

